import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const storybookDir = resolve(here, '..', '.storybook');
const storiesDir = resolve(here, '..', 'src/design/primitives/__stories__');

function listStories(dir) {
  const out = [];
  try {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      if (statSync(full).isFile() && /\.stories\.(ts|tsx)$/.test(name)) out.push(full);
    }
  } catch {
    // no stories dir yet — that's fine, generator emits an empty list.
  }
  return out.sort();
}

const files = listStories(storiesDir);
mkdirSync(storybookDir, { recursive: true });

const imports = files
  .map((f) => {
    const rel = relative(storybookDir, f).replace(/\\/g, '/');
    const importPath = rel.startsWith('.') ? rel : `./${rel}`;
    return `import '${importPath}';`;
  })
  .join('\n');

const body = [
  '// AUTO-GENERATED by scripts/storybook-generate.mjs — do not edit.',
  "import { view } from '@storybook/react-native';",
  imports,
  '',
  'export { view };',
  '',
]
  .filter(Boolean)
  .join('\n');

writeFileSync(resolve(storybookDir, 'storybook.requires.ts'), `${body}\n`);
console.log(`storybook-generate: wrote ${files.length} story imports`);

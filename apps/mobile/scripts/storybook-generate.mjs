import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const storybookDir = resolve(here, '..', '.storybook');
// Story sources — keep in sync with .storybook/main.ts `stories` globs.
const storyRoots = [resolve(here, '..', 'src/design'), resolve(here, '..', 'src/features')];

function listStories(dir) {
  const out = [];
  try {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      const st = statSync(full);
      if (st.isDirectory()) {
        out.push(...listStories(full));
      } else if (st.isFile() && /\.stories\.(ts|tsx)$/.test(name)) {
        out.push(full);
      }
    }
  } catch {
    // no stories dir yet — that's fine, generator emits an empty list.
  }
  return out;
}

const files = storyRoots.flatMap((root) => listStories(root)).sort();
mkdirSync(storybookDir, { recursive: true });

const imports = files
  .map((f) => {
    const rel = relative(storybookDir, f).replace(/\\/g, '/');
    const importPath = rel.startsWith('.') ? rel : `./${rel}`;
    return `import '${importPath}';`;
  })
  .join('\n');

const body = [
  '// AUTO-GENERATED by scripts/storybook-generate.mjs — do not edit.',
  "import { view } from '@storybook/react-native';",
  imports,
  '',
  'export { view };',
  '',
]
  .filter(Boolean)
  .join('\n');

writeFileSync(resolve(storybookDir, 'storybook.requires.ts'), `${body}\n`);
console.log(`storybook-generate: wrote ${files.length} story imports`);
